// **Short paths, because they are what gets typed and pasted.**
//
// Section 17 of `docs/release-readiness.md` asks for direct paths to
// installation, releases, source, security reporting and contribution
// information. These are that: `khoralang.com/install` is a thing somebody can
// say out loud, and it survives the page it points at being reorganised.
//
// The three that leave the site go to files rather than to pages on purpose.
// `SECURITY.md` and `CONTRIBUTING.md` are read by people arriving from a
// vulnerability report or a pull request, and both are places where the
// canonical text is the one in the repository being contributed to.
// **The Guide's pages, where they went.**
//
// `docs/design/docs-urls.md` says a page that moves leaves a redirect, and
// fifteen of them moved at once: the Guide taught the same constructs the
// Reference specified, one page against one page, so it was dissolved into the
// Reference and the two sections that were genuinely distinct. These are the
// links already written down in other people's bookmarks and issues.
